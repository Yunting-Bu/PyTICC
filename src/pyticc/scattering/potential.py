# ----------------------------------------------------------------------------------------
def _potential_radial_grid(
    boundaries: Sequence[float],
    half_steps: Sequence[float],
) -> tuple[tuple[float, ...], tuple[float, ...], tuple[RadialSector, ...], NDArray[np.float64]]:
    """Build sectors and their ordered unique endpoint/midpoint support."""
    boundary_values = tuple(float(value) for value in boundaries)
    half_step_values = tuple(float(value) for value in half_steps)
    sectors = build_radial_sectors(boundary_values, half_step_values)
    radial_points = np.empty(2 * len(sectors) + 1, dtype=np.float64)
    radial_points[0] = sectors[0].radial_start
    for index, sector in enumerate(sectors):
        radial_points[2 * index + 1] = sector.radial_mid
        radial_points[2 * index + 2] = sector.radial_end
    return boundary_values, half_step_values, sectors, radial_points


