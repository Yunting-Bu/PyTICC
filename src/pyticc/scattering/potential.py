# ----------------------------------------------------------------------------------------
def prepare_potential(
    system: ScattSystem,
    boundaries: Sequence[float],
    half_steps: Sequence[float],
    *,
    processes: int = 1,
    **quadrature: int | bool | None,
) -> PotentialGrid:
    """Prepare the geometry-specific raw PES grid for one scattering system.

    Inputs:
        system: ScattSystem - prepared fixed-arrangement scattering system
        boundaries: Sequence[float] - radial interval boundaries in bohr
        half_steps: Sequence[float] - propagation half-step in each interval
        processes: int - worker processes used for the radial PES batch
        quadrature: int | bool | None - geometry-specific quadrature options

    Returns:
        potential_grid: PotentialGrid - raw PES values on all propagation points
    """
    from pyticc.scattering.model import get_scattering_model
    from pyticc.system import ScattSystem

    if not isinstance(system, ScattSystem):
        message = "prepare_potential requires a ScattSystem"
        logger.error(message)
        raise TypeError(message)

    if system.scattering_type is None:
        message = "prepare_potential requires a system built with an explicit scattering_type"
        logger.error(message)
        raise TypeError(message)
    n_radial_points = 2 * len(build_radial_sectors(boundaries, half_steps)) + 1
    started = perf_counter()
    logger.info(f"Potential preparation started: type={system.scattering_type.value}, radial_points={n_radial_points}, processes={processes}")
    model = get_scattering_model(system.scattering_type)
    potential_grid = model.prepare_potential(system, boundaries, half_steps, processes=processes, **quadrature)
    logger.info(
        f"Potential preparation complete: type={system.scattering_type.value}, radial_points={n_radial_points}, wall={perf_counter() - started:.3f} s"
    )
    return potential_grid


