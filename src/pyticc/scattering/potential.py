# ----------------------------------------------------------------------------------------
def _require_type(potential_grid: PotentialGrid, scattering_type: ScatteringType) -> None:
    """Require one geometry-specific potential-grid representation."""
    if potential_grid.scattering_type is not scattering_type:
        message = f"Expected a {scattering_type.value} potential grid, but got {potential_grid.scattering_type.value}"
        logger.error(message)
        raise TypeError(message)


